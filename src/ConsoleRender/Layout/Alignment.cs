namespace ConsoleRender;

/// <summary>Horizontal alignment inside the parent area (used when no left/right anchor is set).</summary>
public enum HorizontalAlignment
{
    Left,
    Center,
    Right,
}

/// <summary>Vertical alignment inside the parent area (used when no top/bottom anchor is set).</summary>
public enum VerticalAlignment
{
    Top,
    Middle,
    Bottom,
}

/// <summary>Alignment of text inside a control's own bounds.</summary>
public enum TextAlignment
{
    Left,
    Center,
    Right,
}
